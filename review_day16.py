# -*- coding: utf-8 -*-
"""
复习总结 · 第 16 天（2026-10-30）

今天只学了一样小东西：把数字变好看

  1. round() —— 四舍五入到几位小数
  2. f"{x:.2f}" —— 写报告最常用的格式
  3. :.2f 和 :.1% 是"一家人"

运行方式：直接跑，没有外部文件依赖。
"""

# ============================================================
# 1. round()：四舍五入
# ============================================================
print("===== 1. round() =====")

x = 78.66666666666667

print(round(x))       # 79     ← 不给第二个参数，就取整
print(round(x, 1))    # 78.7   ← 保留 1 位小数
print(round(x, 2))    # 78.67  ← 保留 2 位小数


# ============================================================
# 2. :.2f 格式化 —— 写报告最常用
# ============================================================
print("===== 2. :.2f =====")

print(f"{x:.2f}")     # 78.67
print(f"{x:.1f}")     # 78.7
print(f"{12.5:.2f}")  # 12.50  ← 注意：位数不够会补 0

# 花括号后面的格式，跟学过的 :.1% 是一家人：
#   :.1%   → 百分数，1 位小数
#   :.2f   → 小数，2 位
# 都是"冒号 + 点 + 位数 + 类型"。


# ============================================================
# 3. 用在报告里
# ============================================================
print("===== 3. 用在电压统计里 =====")

voltages = [12.5, 220, 3.3]
avg = sum(voltages) / len(voltages)

print(f"平均电压:{avg:.2f} V")          # 平均电压:78.60 V
print(f"最大电压:{max(voltages):.2f} V")  # 最大电压:220.00 V
print(f"最小电压:{min(voltages):.2f} V")  # 最小电压:3.30 V

# 对比一下"没用格式"时长的样子：
print(avg)                             # 78.6
print(sum(voltages) / len(voltages))   # 78.6


# ============================================================
# 4. round 与 :.2f 怎么选
# ============================================================
# round(x, 2) → 交给你一个新的数字，可以继续算
# f"{x:.2f}"  → 交给你一段文字，只能打印/写文件
#
# 要接着算，用 round；要显示/写报告，用 :.2f。


print()
