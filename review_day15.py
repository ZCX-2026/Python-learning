# ============================================================
# 1. float() 基础
# ============================================================
print("===== 1. float() 基础 =====")

print(float("12.5"))      # 12.5
print(float("220"))       # 220.0   ← 整数它也收，会变成小数形式
print(int("220"))         # 220

# int("12.5")             # 💥 报错：int 只认整数，不认小数点
# 一句话：int 挑剔，float 什么数字都收。


# ============================================================
# 2. 实操：从一行数据里取小数
# ============================================================
print("===== 2. 取带小数的电压 =====")

line = "节点A,12.5"
parts = line.split(",")               # 盒子
print(parts)                          # ['节点A', '12.5']
print(float(parts[1]))                # 12.5
print(float(parts[1]) * 2)            # 25.0


# ============================================================
# 3. 顺手：用 float 读一份带小数的数据
# ============================================================
print("===== 3. 读带小数的 CSV =====")

with open("_demo_day15.csv", "w", encoding="utf-8") as f:
    f.write("节点A,12.5\n")
    f.write("节点B,220\n")
    f.write("节点C,3.3\n")

voltages = []
with open("_demo_day15.csv", encoding="utf-8") as f:
    for line in f:
        line = line.strip()
        if line == "":
            continue
        parts = line.split(",")
        if len(parts) != 2:
            continue
        # 注意：这里不能再用 isdigit() 当岗哨 —— "12.5" 会被它判成"不是数字"
        voltages.append(float(parts[1]))

print(voltages)                            # [12.5, 220.0, 3.3]
print(f"平均电压:{sum(voltages) / len(voltages)}")   # 78.6


# ============================================================
# 4. 预告：isdigit() 的短板
# ============================================================
print("===== 4. 预告 =====")

print("12.5".isdigit())     # False  ← 它是"纯整数"检测，小数会被误杀
print("220".isdigit())      # True
print("节点A".isdigit())     # False

# 所以数据里一旦有小数，"isdigit 岗哨"就不好用了。
# 明天讲一个能兜住"12.5"的写法。


