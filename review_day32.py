print("===== 4. math 与 random =====")

import math
import random

print("开方:", math.sqrt(25))        # 5.0
print("向下取整:", math.floor(3.7))  # 3
print("向上取整:", math.ceil(3.2))   # 4
print("圆周率:", math.pi)            # 3.14159...

print("随机整数:", random.randint(1, 10))          # 1~10 之间
print("随机挑一个:", random.choice(["甲", "乙", "丙"]))

# random 每次跑结果都不一样 —— 这是它和 math 最大的区别。
# math 是"给定输入必定同样输出"，random 是"故意不一样"。


