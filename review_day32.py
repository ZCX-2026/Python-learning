# ============================================================
# 三、三种写法
# ============================================================
print("===== 2. 三种写法 =====")

# ① 整箱搬进来：拿到 math 这个名字
import math
print("①", math.sqrt(9))          # 3.0

# ② 只拿一个工具：拿到 sqrt 这个名字，没有 math
from math import sqrt
print("②", sqrt(9))               # 3.0

# ③ 整箱搬进来但改个短名
import math as m
print("③", m.sqrt(9))             # 3.0

# 三种写法输出一样 —— 因为是同一个函数。
# 区别在"名字"。


# ============================================================
# 四、关键区别（今天亲眼看到的报错）
# ============================================================
print("===== 3. 关键区别 =====")

# 下面这几行会报错，所以注释掉了。你可以取消注释跑一次：
#
#     from math import sqrt
#     print(sqrt(9))          # ✓ 3.0
#     print(math.sqrt(9))     # ✗ NameError: name 'math' is not defined
#
# 报错原文：
#     NameError: name 'math' is not defined. Did you forget to import 'math'?
#
# 为什么？
#     import math               → 拿到【math】这个名字（整个箱子）
#     from math import sqrt     → 只拿到【sqrt】这个名字（一把工具）
#
# 所以 `from math import sqrt` 之后，`math` 这个名字根本不存在。

print("这一节请自己取消注释跑一次，看到 NameError 才算记住")


