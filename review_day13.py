"""
复习总结 · 第 13 天（2026-10-27）

今日主题：
  1. 复习：split 只"切"不"转" —— 切出来的每一段永远是字符串
  2. 复习：坏数据 `节点A,` 报错在"取"，不在"切"
  3. 新课：isdigit() —— 先问一句"你是纯数字吗"，再决定转不转
  4. 岗哨位置：切之后、取之前
  5. 预告坑：某行没有逗号时，parts[1] 会越界

运行方式：直接跑。会生成 _demo_day13.csv
"""

# ============================================================
# 1. 复习：split 只切不转
# ============================================================
print("===== 1. split 只切不转 =====")

parts = "节点A,220".split(",")

print(parts)              # ['节点A', '220']   ← 整体是【列表】
print(parts[0])           # 节点A              ← 字符串
print(parts[1])           # 220                ← 也是字符串，不是数字！
print(int(parts[1]))      # 220                ← 这才变成数字

# 记住：
#   split 只负责"切"，不负责"转"。
#   要数字，必须自己 int()。


# ============================================================
# 2. 复习：坏数据 `节点A,` 错在哪一步
# ============================================================
print("===== 2. 坏数据错在哪一步 =====")

bad = "节点A,"
bad = bad.strip()             # 脱 → '节点A,'      没问题
print(bad == "")              # 判 → False          不是空行，不跳过
pieces = bad.split(",")       # 切 → ['节点A', '']  切成功了！
print(pieces)                 # 第二段是"空字符串"
# int(pieces[1])              # 取 → int('') 💥 这里才报错，先注释掉别跑

# 结论：切不会报错，空字符串也算"一段"。
#       报错的是"把空字符串转成数字"这一步。


# ============================================================
# 3. 新课：isdigit() —— 你是纯数字吗？
# ============================================================
print("===== 3. isdigit() =====")

print("220".isdigit())       # True   ← 全是 0~9
print("".isdigit())          # False  ← 空的
print("节点A".isdigit())      # False  ← 有汉字
print("12.5".isdigit())      # False  ← 小数点不是数字字符！

# isdigit() 交给你 True 或 False，正好能塞进 if 里当门卫。
# 注意：它只认"纯整数"。带小数点的一律 False，以后处理小数用 float()。


# ============================================================
# 4. 岗哨位置：切之后、取之前
# ============================================================
print("===== 4. 把坏数据挡在门外 =====")

# 造一个演示文件，里面故意混了一行坏数据（节点C 的电压是空的）
with open("_demo_day13.csv", "w", encoding="utf-8") as f:
    f.write("节点A,220\n")
    f.write("节点B,380\n")
    f.write("节点C,\n")          # ← 坏数据
    f.write("节点D,1500\n")

names = []                        # 篮子建在循环外面
voltages = []

with open("_demo_day13.csv", encoding="utf-8") as f:
    for line in f:
        line = line.strip()                  # 脱
        if line == "":                       # 判
            continue
        parts = line.split(",")              # 切
        if parts[1].isdigit():               # 岗哨：确认是纯数字
            names.append(parts[0])           # 取
            voltages.append(int(parts[1]))
        # 不是数字 → 什么都不做，自动进入下一行

print(names)      # ['节点A', '节点B', '节点D']
print(voltages)   # [220, 380, 1500]
print("节点C 被跳过了，因为它的电压不是数字")


