# ============================================================
# 1. 复习：len 与 count
# ============================================================
print("===== 1. len 与 count =====")

nodes = [220, 380, 220, 12, 220]
print(len(nodes))               # 5  ← 一共几个
print(nodes.count(220))         # 3  ← 220 出现几次

# 字符串也能 count：数某个字符出现了几次
print("节点A,220".count("2"))    # 2

# 忘了小括号时，屏幕会打出方法本身，而不是结果
print(nodes.count)              # <built-in method count of list object at 0x...>
# 看到 <built-in method ...> 这种尖括号开头的，就是漏了 ()


# ============================================================
# 2. 新课：两个篮子并排存
# ============================================================
print("===== 2. 两个篮子并排存 =====")

# 先造一个演示文件：每行格式是 "节点名,电压"
with open("_demo_day12.csv", "w", encoding="utf-8") as f:
    f.write("节点A,220\n")
    f.write("节点B,380\n")
    f.write("节点C,1500\n")

names = []        # 篮子一：节点名     ← 建在循环外面，只建一次
voltages = []     # 篮子二：电压

with open("_demo_day12.csv", encoding="utf-8") as f:
    for line in f:
        line = line.strip()                 # 脱
        if line == "":                      # 判
            continue
        parts = line.split(",")             # 切
        names.append(parts[0])              # 取：左边那段进名字篮子
        voltages.append(int(parts[1]))      # 取：右边那段转数字进电压篮子

print(names)        # ['节点A', '节点B', '节点C']
print(voltages)     # [220, 380, 1500]


# ============================================================
# 3. 位置对齐：两个列表靠"位置相同"配合工作
# ============================================================
print("===== 3. 位置对齐 =====")

# names[0] 和 voltages[0] 是同一条记录
print(names[1], voltages[1])    # 节点B 380

# 正是因为位置一一对应，才能这样一条条对出来：
print(f"位置0: {names[0]} = {voltages[0]}V")
print(f"位置1: {names[1]} = {voltages[1]}V")
print(f"位置2: {names[2]} = {voltages[2]}V")


# ============================================================
# 4. 用两个列表算统计
# ============================================================
print("===== 4. 统计 =====")

print(sum(voltages) / len(voltages))    # 700.0  平均电压
print(max(voltages))                    # 1500
print(min(voltages))                    # 220


# ============================================================
# 5. 今天的重点坑：篮子放哪，三种命运
# ============================================================
#   ① 0 格（最外面）        → 只建一次，装三次        ✓ 正确
#   ② 8 格（for 里）        → 每圈换新篮子            ✗ 不报错，但只剩最后一个
#   ③ 12 格（continue 后面）→ 永远执行不到            ✗ NameError 报错
#
# 记住：报错的不一定最危险；
#       不报错、但结果悄悄错的（②），才最难发现。
#
# 规矩：凡是"累加、收集、统计"的篮子，一律放在循环外面。
#       result = []   total = 0   high = []   全都是这个道理。

print()
