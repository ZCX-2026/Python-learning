print("2. <built-in method ...> = 忘了小括号")
print("3. 一行数据有两个字段 → 用两个篮子，分别 append")
print("4. 两个列表靠位置对齐：names[1] 和 voltages[1] 是同一条记录")
print("5. 篮子必须建在循环外面，否则每圈换新的（还不报错）")
print("6. 读一行数据的固定顺序：脱 → 判 → 切 → 取")