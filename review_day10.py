# ============================================================
# 1. 循环写文件
# ============================================================
print("===== 1. 循环写文件 =====")

numbers = [2100, 1600, 1050]

with open("_demo_lines.txt", "w", encoding="utf-8") as f:
    for x in numbers:              # for 决定"写几次"
        f.write(f"{x}\n")          # \n 决定"每行结束"

print("已写入 _demo_lines.txt（3 行，每行一个数）")

# 两个错误示范（只写在注释里，别取消注释）：
#   f.write(numbers)        → 报错：write 只收字符串，不收列表
#   f.write(f"{x}")         → 少了 \n，三个数会粘成一行 210016001050


# ============================================================
# 2. split() 把一行切开
# ============================================================
print("===== 2. split 切开 =====")

line = "节点A,220"
parts = line.split(",")            # 小括号里放分隔符
print(parts)                       # ['节点A', '220']
print(parts[0])                    # 节点A
print(parts[1])                    # 220  ← 注意：这仍然是字符串
print(int(parts[1]) + 1)           # 221  ← 转成数字才能算

# 今天踩的坑：中括号是列表，引号才是字符串
#   line = ["节点A,220"]   ← 这是"列表里装了一条字符串"
#   line.split(",")        ← 报错：列表身上没有 split 这个功能


# ============================================================
# 3. CSV 骨架：读一行 → 切开 → 取需要的字段
#    （这就是你今天没写出来的第 3 步）
# ============================================================
print("===== 3. CSV 骨架 =====")

# 先造一个演示用的 CSV 文件：每行格式是 "节点名,电压"
with open("_demo_nodes.csv", "w", encoding="utf-8") as f:
    f.write("节点A,220\n")
    f.write("节点B,380\n")
    f.write("节点C,1500\n")

voltages = []                              # 空篮子
with open("_demo_nodes.csv", encoding="utf-8") as f:
    for line in f:
        line = line.strip()                # ① 先脱换行（别忘了小括号）
        if line == "":                     # ② 空行跳过
            continue
        parts = line.split(",")            # ③ 按逗号切成两段
        voltages.append(int(parts[1]))     # ④ 取第 2 段（电压）转成数字

print(voltages)                            # [220, 380, 1500]


# ============================================================
# 4. 串联：CSV 读进来 → 筛选 → 交给下一步
# ============================================================
print("===== 4. 串联：CSV → 筛选 =====")

high = []
for v in voltages:
    if v >= 1000:
        high.append(v)
print(high)                                # [1500]

# 这一步就是以后 "CSV → 统计 → 出报告" 腰眼上的那块


