# ============================================================
# 第一讲：len 到底在数什么
# ============================================================
print("===== 第一讲：len 数什么 =====")

print(len("220"))                    # 3  ← 字符串：数"字符"（2、2、0）
print(len("220".split(",")))         # 1  ← 列表：数"元素"，只有 1 段
print(len("a,b,c".split(",")))       # 3  ← 两个逗号切成 3 段
print(len(["abc"]))                  # 1  ← 列表里只有 1 个元素
print(len(["a", "b", "c"]))          # 3

# 核心：len 数的是"最外面这一层装了几个东西"
#   "220"       最外层是字符串 → 数字符 → 3
#   ['220']     最外层是列表   → 数元素 → 1
#
# 好记的规则：段数 = 逗号个数 + 1
#   "220"       0 个逗号 → 1 段
#   "a,b,c"     2 个逗号 → 3 段


# ============================================================
# 第二讲：sorted 与 .sort() 的区别
# ============================================================
print("===== 第二讲：sorted 与 .sort() =====")

a = [3, 1, 2]

b = sorted(a)          # 复印一份，把复印件排好给你；原件没动
print(a)               # [3, 1, 2]   ← 原件没变
print(b)               # [1, 2, 3]   ← 新列表

c = a.sort()           # 把原件重新摆好，然后空手走人
print(a)               # [1, 2, 3]   ← 原件被改了
print(c)               # None        ← 它什么都没交

# 记法：
#   sorted(a)  复印排序 → 交给你新列表，不动原件
#   a.sort()   原地重排 → 动了原件，但空手（None）
#
# 活干了 ≠ 有货交。这跟 write_report 写了文件但返回 None 是同一回事。


# ============================================================
# 第三讲：try / except 怎么走
# ============================================================
print("===== 第三讲：try / except =====")

for s in ["10", "abc", "20"]:
    try:
        print("A", s)          # 进 try 第一行，一定执行
        v = float(s)           # 可能在这里炸
        print("B", v)          # ← 炸了的话，这行不执行！
    except ValueError:
        print("C", s)          # 出错后跳到这里

# 实际输出（6 行）：
#   A 10
#   B 10.0
#   A abc        ← 进来先打印 A
#   C abc        ← float("abc") 炸了，B 被跳过，直接到 except
#   A 20
#   B 20.0
#
# 最关键的一条：
#   try 里只要有一行出错，它后面的行全部不执行，直接跳到 except。


# ============================================================
# 第三讲续：pass 与 continue 的区别
# ============================================================
print("===== pass 与 continue =====")

print("用 continue（正确）：整行丢弃")
names = []
voltages = []
lines = ["节点A,220", "节点B,", "节点C,380"]

for line in lines:
    parts = line.split(",")
    try:
        v = float(parts[1])
    except ValueError:
        continue                  # ← 这一圈不要了，名字和电压都不收
    names.append(parts[0])
    voltages.append(v)

print(names)      # ['节点A', '节点C']
print(voltages)   # [220.0, 380.0]     ← 两个列表长度一致，位置对齐


# 换成 pass 会怎样（只在注释里演示，别运行）：
#
#     except ValueError:
#         pass                  ← 出错了但继续往下走
#     names.append(parts[0])    ← 名字照样进篮子
#     voltages.append(v)        ← v 是"上一圈留下的旧值"（或根本没定义）
#
# 结果：名字 3 个、电压 3 个，但节点B 用的是节点A 的电压 → 悄悄错位
#
# 一句话：
#   pass     = 出错了，但接着往下走（危险）
#   continue = 出错了，这一圈不要了（安全）


