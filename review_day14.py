# -*- coding: utf-8 -*-
"""
复习总结 · 第 14 天（2026-10-28）

今日主题：
  1. 复习：split 给你的是一个"盒子（列表）"，盒子里每一格才是字符串
  2. 复习：len 数什么，看它套在字符串还是列表身上
  3. 新课：段数岗哨 len(parts) != 2 —— 不只防"少了"，也防"多了"
  4. 三道岗合体：空行 / 段数不对 / 不是数字

运行方式：直接跑。会生成 _demo_day14.csv
"""

# ============================================================
# 1. 复习：split 给的是盒子，不是绳子
# ============================================================
print("===== 1. split 给的是盒子 =====")

parts = "节点A,220".split(",")
print(parts)          # ['节点A', '220']   ← 有中括号！这是【列表】
print(parts[0])       # 节点A              ← 盒子里第 0 格，字符串
print(parts[1])       # 220                ← 盒子里第 1 格，还是字符串
print(int(parts[1]))  # 220                ← 转成数字

# 记住这个比喻：
#   split = 把一根绳子剪成几段，装进一个盒子递给你
#   盒子      → 列表（parts）
#   盒子里的格子 → 字符串（parts[0]、parts[1]）


# ============================================================
# 2. 复习：len 数什么
# ============================================================
print("===== 2. len 数什么 =====")

print(len("220"))                       # 3  ← 字符串：数"字符"
print(len("220".split(",")))            # 1  ← 列表：数"元素"，只有 1 段
print(len("节点A,220".split(",")))      # 2  ← 列表：两段

# 一个 3 一个 1，差在 split 有没有生效：
#   没 split → 字符串 → 数字符
#   split 过 → 列表   → 数元素


# ============================================================
# 3. 新课：段数岗哨
# ============================================================
print("===== 3. 段数岗哨 =====")

print(len("220".split(",")))            # 1  ← 没有电压段，不能收
print(len("节点A,220".split(",")))      # 2  ← 标准格式，能收
print(len("节点A,220,合格".split(","))) # 3  ← 多一段，也不能收

# 所以判据是  len(parts) != 2
# 用 < 2 会把"多一段"的脏数据漏进来。
# 不只防"少了"，还要防"多了"。


# ============================================================
# 4. 三道岗合体（完整可跑）
# ============================================================
print("===== 4. 三道岗合体 =====")

# 故意造一份脏数据：空行、没逗号、空电压、多一段，全都有
with open("_demo_day14.csv", "w", encoding="utf-8") as f:
    f.write("节点A,220\n")
    f.write("节点B,380\n")
    f.write("\n")                # 脏：空行
    f.write("节点C,1500\n")
    f.write("220\n")             # 脏：没逗号
    f.write("节点D,\n")          # 脏：电压是空的
    f.write("节点E,660,合格\n")   # 脏：多了一段
    f.write("节点F,1000\n")

names = []          # 篮子建在循环外面：只建一次
voltages = []

with open("_demo_day14.csv", encoding="utf-8") as f:
    for line in f:
        line = line.strip()                  # 脱
        if line == "":                       # 岗一：空行
            continue
        parts = line.split(",")              # 切
        if len(parts) != 2:                  # 岗二：段数不对
            continue
        if parts[1].isdigit():               # 岗三：不是纯数字
            names.append(parts[0])           # 取
            voltages.append(int(parts[1]))
        # 三道岗全过 → 才是干净数据

print(names)        # ['节点A', '节点B', '节点C', '节点F']
print(voltages)     # [220, 380, 1500, 1000]
print(f"平均电压:{sum(voltages) / len(voltages)}")   # 775.0
print("上面 4 行脏数据，全部被三道岗挡在门外")


print()
print("===== 第 14 天小结 =====")
print("1. split 给的是列表（盒子），盒子里每一格是字符串")
print("2. len 数字符还是数元素，看它套在字符串还是列表身上")
print("3. 段数岗哨用 len(parts) != 2，少了多了都挡")
print("4. 三道岗：空行 → 段数不对 → 不是数字")
print("5. 这就是「数据清洗」的完整骨架，以后读任何数据都是它")