"""
复习总结 · 第 21 天（2026-11-04）

今天只有 20 分钟，学了一样：函数怎么一次交回两样东西。

  1. return 甲, 乙        用逗号打包成一个"元组"
  2. x = f()              x 拿到的是整个包裹（带圆括号）
  3. a, b = f()           用逗号拆包，才拿到两个分开的值
  4. 元组也能用 len 和下标取
  5. 三种常见错法

运行方式：直接跑，没有外部文件依赖。
"""

# ============================================================
# 1. 打包：return 后面写逗号
# ============================================================
print("===== 1. 打包 =====")


def give_two():
    return 1, 2          # 逗号 → 打包成一个整体交出去


x = give_two()
print(x)                 # (1, 2)   ← 圆括号就是"包裹"的外壳
print(len(x))            # 2        ← 它是一个装着 2 个东西的容器
print(x[0])              # 1        ← 容器也能用下标取
print(x[1])              # 2

# 关键：x 是"一个东西"，不是两个变量。
# 所以 print(x) 打印的是这个容器的样子，自带圆括号。


# ============================================================
# 2. 拆包：左边也用逗号
# ============================================================
print("===== 2. 拆包 =====")

a, b = give_two()        # 逗号 → 把包裹拆开
print(a)                 # 1
print(b)                 # 2
print(a, b)              # 1 2   ← 这里是"传两个参数给 print"，中间空格

# 注意下面两个逗号，作用完全不同：
#   return 1, 2      逗号在"打包"
#   print(a, b)      逗号在"传两个参数"
# 长得一样，干的事不一样。


# ============================================================
# 3. 三种常见错法
# ============================================================
print("===== 3. 三种错法 =====")

# 错法一：用一个变量接，以为接到的是一样东西
#     x = give_two()
#     print(x + 1)        → 报错：元组不能和数字相加
#     （x 是整个 (1, 2)，不是 1）

# 错法二：变量个数对不上
#     a, b, c = give_two()   → 报错：not enough values to unpack
#     （只有 2 个，却要用 3 个接）

# 错法三：顺序接反（不报错，但全错）
#     def f():
#         return "名字", 220
#     v, n = f()          → v 变成了 "名字"，n 变成了 220
#     （左边按 return 的顺序接，接反了不会提醒你）


# ============================================================
# 4. 用在 read_csv 上（你明天要用到的形状）
# ============================================================
print("===== 4. read_csv 一次交回两个列表 =====")


def read_csv(filename):
    """读 CSV（每行：名字,电压），返回两个列表。"""
    names = []
    voltages = []
    with open(filename, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line == "":
                continue
            parts = line.split(",")
            if len(parts) != 2:
                continue
            try:
                v = float(parts[1])
            except ValueError:
                continue
            names.append(parts[0])
            voltages.append(v)
    return names, voltages          # 逗号打包


with open("_demo_day21.csv", "w", encoding="utf-8") as f:
    f.write("节点A,220\n")
    f.write("节点B,380\n")
    f.write("节点C,12.5\n")

names, voltages = read_csv("_demo_day21.csv")   # 逗号拆包
print(names)        # ['节点A', '节点B', '节点C']
print(voltages)     # [220.0, 380.0, 12.5]

# 为什么这个函数要交两样？
# 因为 names[0] 和 voltages[0] 必须是同一条记录 —— 它们要成对使用。


