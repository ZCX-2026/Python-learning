# ============================================================
# 1. 为什么拆成四个函数
# ============================================================
print("===== 1. 为什么拆 =====")

# 一个函数只干一件事：
#     make_demo_file()   造数据
#     read_nodes()       读 + 清洗 → 返回字典
#     show_stats()       统计
#     write_report()     写文件
#
# 好处不是"好看"，是"换东西只改一处"：
#     换数据源    → 只改 read_nodes
#     换报告格式  → 只改 write_report
#     加个统计项  → 只改 show_stats
#
# 这叫"脚本"和"工具"的区别：
#     脚本是一次性的，用完就扔；
#     工具是能换数据反复用的。


# ============================================================
# 2. 两个列表会错位，字典不会（这段是真能跑出来的）
# ============================================================
print("===== 2. 错位演示 =====")

lines = [
    "节点A,220",
    "节点B,待测",      # ← 名字能读出来，但电压转不了
    "节点C,380",
]

# ---- 写法一：两个列表 ----
names = []
values = []
for line in lines:
    parts = line.split(",")
    names.append(parts[0])          # 名字无条件进篮子
    try:
        v = float(parts[1])
    except ValueError:
        continue                    # 电压没进篮子 —— 从这一行起就错位了
    values.append(v)

print("两个列表：")
print("  names  =", names)          # 3 个
print("  values =", values)         # 2 个
print("  → 名字和电压对不上了！而且程序没报错")

# ---- 写法二：字典 ----
info = {}
for line in lines:
    parts = line.split(",")
    try:
        v = float(parts[1])
    except ValueError:
        continue                    # 整条丢掉，名字也不会进
    info[parts[0]] = v              # 名字和值在同一行完成绑定

print("字典：")
print("  info =", info)
print("  → 不存在错位，因为存进去这件事是「一次完成」的")

# 一句话：
#   两个列表 = 两张纸，靠你自己保证对齐；
#   字典     = 一张纸，名字和值写在同一个格子里。


# ============================================================
# 3. 四道岗，各挡什么
# ============================================================
print("===== 3. 四道岗 =====")

# 岗一  if line == "":            空行
#       真实来源：手动编辑留下的空行、程序写入时的末尾空行
#
# 岗二  if len(parts) != 2:       段数不对
#       真实来源：没逗号（"220"）、多一段（"电梯,660,合格"）
#
# 岗三  try: float(...)           转不了数字
#       真实来源：空值（"风机,"）、文字标注（"风机,待测"）
#
# 岗四  info[名字] = 电压          成对进出
#       靠字典天然保证，不用你额外写代码
#
# 少任何一道，脏数据都会混进统计里，而且多半不报错。


# ============================================================
# 4. 空数据必须先判断
# ============================================================
print("===== 4. 空数据 =====")


def show_stats(info):
    if len(info) == 0:                    # ← 这一行是保命的
        print("没有读到任何数据")
        return
    print(f"共 {len(info)} 个回路")
    print(f"平均:{sum(info.values()) / len(info):.2f}")
    print(f"最高:{max(info.values())}  最低:{min(info.values())}")


show_stats({})                                  # 空字典 → 走保命分支，不崩
show_stats({"节点A": 220.0, "节点B": 380.0})     # 正常数据

# 不判断会怎样（别取消注释）：
#     sum({}.values()) / len({})   → 0 / 0   → 除零报错
#     max({}.values())             → 空序列   → 报错
#
# 空数据看起来是小事，其实是真实项目里最容易崩的地方之一。


# ============================================================
# 5. 写文件三要点
# ============================================================
print("===== 5. 写文件 =====")

# ① "w" 一打开就清空 —— 别拿有数据的文件当靶子
# ② f.write 不会自动换行 —— 每行末尾自己加 \n
# ③ write_report 没有 return —— 调用时不要用 = 接

with open("_demo_day24.txt", "w", encoding="utf-8") as f:
    f.write("第一行\n")
    f.write("第二行\n")

with open("_demo_day24.txt", encoding="utf-8") as f:
    print(f.read())            # read() 一次性读完；不要和 for line in f 混用


