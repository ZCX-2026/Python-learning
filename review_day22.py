# -*- coding: utf-8 -*-
"""
复习总结 · 第 22 天（2026-11-05）  字典（dict）

今天只有半小时，只学了字典的核心三件事：
  1. 取值：[] / in / get 三种写法，谁安全谁危险
  2. 存值：d["键"] = 值 —— 新增和修改是同一种写法
  3. 遍历：for 名字, 值 in d.items() —— 又是一次"拆包"

重点详解放在第 2、3、4 段（就是课上问的那几个问题）。

运行方式：直接跑，没有外部文件依赖。
"""

# ============================================================
# 1. 字典是什么
# ============================================================
print("===== 1. 字典是什么 =====")

# 中括号 [] 是列表，大括号 {} 是字典
voltages = {
    "进线柜": 380,
    "照明回路": 220,
    "备用电源": 110,
}

print(voltages)

# 它是一张"对照表"：
#     进线柜   → 380
#   照明回路   → 220
#   备用电源   → 110
#
# 左边叫"键"，右边叫"值"。
# 列表按【位置】取（voltages[0]），字典按【名字】取（voltages["进线柜"]）。


# ============================================================
# 2. 【重点】三种取值方式，谁安全谁危险
# ============================================================
print("===== 2. 取值：[] / in / get =====")

# ① 方括号：硬取。没有就直接翻脸。
print(voltages["进线柜"])          # 380

# ② in：问路。只回答"在不在"，永远不报错。
print("进线柜" in voltages)        # True
print("电梯" in voltages)          # False

# ③ get()：试探。有就给我，没有就给 None；还能指定默认值。
print(voltages.get("进线柜"))      # 380
print(voltages.get("电梯"))        # None
print(voltages.get("电梯", 0))     # 0

# 下面这一行会炸，所以注释掉了：
# print(voltages["电梯"])
#   → KeyError: '电梯'
#   报错名字就叫 KeyError（不是 ValueError）。意思是"没有这个键"。

# ┌──────────────┬──────────────┬─────────────────────────┐
# │ 写法          │ 取不到时      │ 什么时候用                │
# ├──────────────┼──────────────┼─────────────────────────┤
# │ d["键"]       │ 报 KeyError   │ 你确定它一定在             │
# │ "键" in d     │ 返回 False    │ 只想问"在不在"             │
# │ d.get("键")   │ 返回 None     │ 不确定在不在               │
# │ d.get("键", x)│ 返回 x        │ 不确定在不在，还想给个默认值 │
# └──────────────┴──────────────┴─────────────────────────┘
#
# 最容易记错的一点：in 和 get 都【不会】报错，只有 [] 会。


# ============================================================
# 3. 【重点】d["键"] = 值 到底在干什么
# ============================================================
print("===== 3. 存值：d[键] = 值 =====")

# 先把这一行拆开读：
#
#     voltages["空调回路"] = 150
#     └──────┬──────┘   └┬┘
#        存到哪儿         存什么
#
# 读作："把 150 存进 voltages 这个字典里、键叫『空调回路』的位置。"

# 情况一：这个键原来不存在 → 新建一条
print("存之前:", voltages)
voltages["空调回路"] = 150
print("新增后:", voltages)          # 最后多了一条 '空调回路': 150

# 情况二：这个键原来就存在 → 把旧值覆盖掉
voltages["照明回路"] = 230
print("修改后:", voltages)          # '照明回路' 从 220 变成了 230

# 两种情况的写法完全一样，Python 自己判断是"新建"还是"改掉"。
#
# 注意：字典没有 append！
#   voltages.append(...)   ✗  字典不是列表
#   直接 d["键"] = 值      ✓  就是新增


# ============================================================
# 4. 【重点】遍历：for 名字, 值 in d.items()
# ============================================================
print("===== 4. 遍历 =====")

# ① 只拿键
for name in voltages:
    print(name)

print("---")

# ② 同时拿键和值（最常用）
for name, v in voltages.items():
    print(f"{name}: {v}V")

# 这三样东西各是什么：
#   voltages.items()  →  一对一对的东西：(进线柜, 380)、(照明回路, 230)...
#   for name, v in    →  每圈拿一对，name 接左边的键，v 接右边的值
#   这就叫"拆包"，跟你学过的 a, b = f() 是同一个机制
#
# 字典里有几对，这个循环就跑几圈。


# ============================================================
# 5. 顺手复习：怎么把 CSV 存成字典
# ============================================================
print("===== 5. CSV → 字典 =====")

with open("_demo_day22.csv", "w", encoding="utf-8") as f:
    f.write("节点A,220\n")
    f.write("节点B,380\n")
    f.write("节点C,\n")          # 坏数据
    f.write("节点D,1500\n")

info = {}                          # 空字典（不是空列表）
with open("_demo_day22.csv", encoding="utf-8") as f:
    for line in f:
        line = line.strip()
        if line == "":
            continue
        parts = line.split(",")
        if len(parts) != 2:
            continue
        try:
            v = float(parts[1])
        except ValueError:
            continue
        info[parts[0]] = v          # 键 = 节点名，值 = 电压

print(info)          # {'节点A': 220.0, '节点B': 380.0, '节点D': 1500.0}

# 注意：空字典写 {}，不是 []
# 而且这里不需要"两个列表对齐"了，名字和值天生绑在一起。


print()
