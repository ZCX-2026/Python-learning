print("2. 取值三种：d[键] 会报错；in 永不报错；get 安全还能给默认值")
print("3. 存值：d[键] = 值 —— 键不在就新增，在就修改，写法一样")
print("4. 字典没有 append")
print("5. 遍历：for 名字, 值 in d.items() —— 一次拆一对")