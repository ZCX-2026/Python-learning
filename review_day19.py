# ============================================================
# 1. 问题：一个函数只能交回一样东西吗？
# ============================================================
print("===== 1. 一次交回两样 =====")


def give_two():
    a = "甲"
    b = "乙"
    return a, b          # 用逗号打包，交回两样


x, y = give_two()        # 用逗号拆包，按顺序接
print(x)                 # 甲
print(y)                 # 乙

# 顺序对应：
#   return 里第一个 → 左边第一个
#   return 里第二个 → 左边第二个


# ============================================================
# 2. 打印出来长什么样
# ============================================================
print("===== 2. 它其实是一个东西 =====")

print(give_two())        # ('甲', '乙')  ← 外面是圆括号

# 看到没？打印出来是"一个圆括号包着的整体"，不是两个值。
# 这个整体叫"元组"（tuple）。
# 用逗号 return，Python 就把它们打包成一个元组交给你。
# 你在左边用逗号接，Python 就自动拆开 —— 这叫"拆包"。


# ============================================================
# 3. 三种常见错法（都写在注释里，别运行）
# ============================================================
print("===== 3. 三种错法 =====")

# 错法一：只交一样，却用两样去接
#     def f():
#         return 1
#     a, b = f()
#     → 报错：not enough values to unpack（不够拆）

# 错法二：用两样去接，却只写了一个变量
#     def f():
#         return 1, 2
#     a = f()
#     → 不报错，但 a 拿到的是整个元组 (1, 2)，不是 1

# 错法三：顺序搞反
#     def f():
#         return "名字", 220
#     v, n = f()          # 名字和电压接反了
#     → 不报错，但 v 变成了 "名字"，后面全错


# ============================================================
# 4. 完整例子：把"读 CSV"提成函数
# ============================================================
print("===== 4. read_csv：一次交回两个列表 =====")

# 先造一份演示数据（含一行坏数据）
with open("_demo_day19.csv", "w", encoding="utf-8") as f:
    f.write("节点A,220\n")
    f.write("节点B,380\n")
    f.write("节点C,1500\n")
    f.write("节点D,12.5\n")
    f.write("节点E,\n")            # 坏数据：电压是空的


def read_csv(filename):
    """读 CSV（每行：名字,电压），返回两个列表：names 和 voltages。"""
    names = []
    voltages = []
    with open(filename, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line == "":
                continue
            parts = line.split(",")
            if len(parts) != 2:
                continue
            try:
                v = float(parts[1])
            except ValueError:
                continue
            names.append(parts[0])
            voltages.append(v)
    return names, voltages          # 一次交回两样


names, voltages = read_csv("_demo_day19.csv")   # 一次接两样
print(names)        # ['节点A', '节点B', '节点C', '节点D']
print(voltages)     # [220.0, 380.0, 1500.0, 12.5]


# ============================================================
# 5. 接住之后，想怎么用就怎么用
# ============================================================
print("===== 5. 接住之后 =====")

print(f"共 {len(voltages)} 个节点")
print(f"平均电压:{sum(voltages) / len(voltages):.2f}")
print(f"最高:{max(voltages)}  最低:{min(voltages)}")

# 注意：names 和 voltages 是"并排对齐"的
#   names[0] 和 voltages[0] 是同一条记录
# 这就是为什么 read_csv 要一次交回两个列表 —— 它们必须成对使用。


