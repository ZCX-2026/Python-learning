# ============================================================
# 一、为什么需要类
# ============================================================
# 假设有 3 个球员，每个有名字和号码。
#
# 用两个列表：        names = [...] / nums = [...]      ← 又要靠位置对齐
# 用三个字典：        p1 = {"name": ..., "num": ...}    ← 每个都要重写键名
# 用类：              先定一张"图纸"，再照着造
#
# 类 = 图纸；对象 = 照图纸造出来的东西


# ============================================================
# 二、最小可用的类
# ============================================================


class Player:
    def __init__(self, name, num):
        """__init__ = 造对象时自动执行的"装配步骤"。"""
        self.name = name       # 把参数 name 存到"这个对象"身上
        self.num = num         # 把参数 num  存到"这个对象"身上

    def show(self):
        """show = 对象能做的一个动作（方法）。"""
        print(f"{self.num}号 {self.name}")


# ============================================================
# 三、造对象、用对象
# ============================================================
p1 = Player("小明", 7)
p2 = Player("小红", 8)
p3 = Player("小刚", 11)

p1.show()      # 7号 小明
p2.show()      # 8号 小红
p3.show()      # 11号 小刚

# 也可以直接取属性
print(p1.name)      # 小明
print(p1.num)       # 7


# ============================================================
# 四、三个必须记住的点
# ============================================================
#
# ① __init__ 是"暗号"，名字固定，不能改名
#      __init__   创建对象时自动执行
#      __int__    转成整数时执行（完全另一回事）
#      少写一个 i，Python 就认不出，报"takes no arguments"
#
# ② self = "这个对象自己"
#      p1.show() 执行时，self 指向 p1
#      p2.show() 执行时，self 指向 p2
#      调用时不用传 self，Python 自动塞
#
# ③ 缩进：方法必须在类里面（4 格），调用必须在类外面（0 格）
#
#      class Player:           ← 0 格
#          def __init__:       ← 4 格（类里面）
#              self.name = ... ← 8 格（方法里面）
#
#          def show:           ← 4 格
#              print(...)      ← 8 格
#
#      p1 = Player(...)        ← 0 格（类外面）
#      p1.show()               ← 0 格


# ============================================================
# 五、今天踩的两个坑
# ============================================================
#
# 坑 1：写成 __int__（四个字母），Python 认不出 → takes no arguments
#       正确：__init__（五个字母）
#
# 坑 2：把 p1 = Player(...) 顶格写在类中间，然后 def show 缩进 4 格
#       → IndentationError: unexpected indent（意外缩进）
#       原因：刚才还是 0 格，突然变成 4 格，Python 不接受
#       解决：类里只放定义，调用全部放到类后面


